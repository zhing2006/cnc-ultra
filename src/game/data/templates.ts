/**
 * The CLEAR1 icon a cell without a template shows, which varies with the cell's position. Ported from
 * CELL.CPP, CellClass::Clear_Icon. The cell number packs y * 64 + x.
 */
export function clearIcon(x: number, y: number): number {
  return (x & 0x03) | ((y << 2) & 0x0c);
}
