const types = new Map(rows.map(([name, normal, alternate, icons]) => [name, {normal, alternate, icons}]));

/** Ported from CELL.CPP, CellClass::Recalc_Attributes (template part). */
export function templateLand(name: string, icon: number): number {
  const type = types.get(name);
  return type ? (type.icons.includes(icon) ? type.alternate : type.normal) : 0;
}

/** Ported from CONST.CPP, Ground; nonzero tracked/foot movement entries. */
export const WALKABLE_LAND = [true, true, false, false, false, true, true];

/** Ported from CDATA.CPP and CONST.CPP, Ground: only clear ground and roads permit construction. */
export function buildableTemplate(name: string, icon: number): boolean {
  const land = templateLand(name, icon);
  return land === 0 || land === 1;
}
