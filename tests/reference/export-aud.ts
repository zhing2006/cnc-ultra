// Export independent PCM digests from the pinned OpenRA decoder. No decoded audio is committed.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root=new URL('../../',import.meta.url),helper=new URL('refs/openra-aud/',root);
mkdirSync(helper,{recursive:true});
writeFileSync(new URL('Export.csproj',helper),`<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><OutputType>Exe</OutputType><TargetFramework>net9.0</TargetFramework></PropertyGroup><ItemGroup>
${['OpenRA.Game','OpenRA.Mods.Common','OpenRA.Mods.Cnc'].map(name=>`<Reference Include="${name}"><HintPath>../source/openra/bin/${name}.dll</HintPath></Reference>`).join('\n')}
</ItemGroup></Project>`);
writeFileSync(new URL('Program.cs',helper),`using System;
using System.IO;
using System.Security.Cryptography;
using OpenRA.Mods.Cnc.FileFormats;
class Export {
  static void Main(string[] args) {
    var bytes=File.ReadAllBytes(args[0]);
    int count=BitConverter.ToUInt16(bytes,0),start=6+count*12;
    for(int i=0;i<count;i++) {
      int p=6+i*12,offset=start+BitConverter.ToInt32(bytes,p+4),size=BitConverter.ToInt32(bytes,p+8);
      using var stream=new MemoryStream(bytes,offset,size);
      if(!AudReader.LoadSound(stream,out var open,out var rate,out var bits,out var channels,out var duration))continue;
      using var pcm=open();using var data=new MemoryStream();pcm.CopyTo(data);
      Console.WriteLine($"{BitConverter.ToUInt32(bytes,p):x8} {rate} {bits} {channels} {Convert.ToHexString(SHA256.HashData(data.ToArray())).ToLowerInvariant()}");
    }
  }
}`);
execFileSync('dotnet',['build','Export.csproj','-c','Release','--nologo','-v','quiet'],{cwd:fileURLToPath(helper),stdio:'inherit'});
const output=execFileSync('dotnet',[fileURLToPath(new URL('bin/Release/net9.0/Export.dll',helper)),fileURLToPath(new URL('assets/dev/sounds.mix',root))],{encoding:'utf8'});
writeFileSync(new URL('openra-aud.txt',import.meta.url),'# PCM digests from the pinned OpenRA AudReader; generated by export-aud.ts.\n# MIX ID, sample rate, bits, channels, SHA-256 of decoded PCM.\n'+output.replaceAll('\r\n','\n'));
console.log(`Exported ${output.trim().split(/\r?\n/).length} AUD digests.`);
